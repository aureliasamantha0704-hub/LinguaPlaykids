export function getVocabularyByTopic(topicId: TopicId): VocabularyItem[] {
  return VOCABULARY_LIST.filter((v) => v.topic === topicId);
}

export function getRandomVocabulary(count: number, topicId?: TopicId): VocabularyItem[] {
  const pool = topicId ? getVocabularyByTopic(topicId) : [...VOCABULARY_LIST];
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
